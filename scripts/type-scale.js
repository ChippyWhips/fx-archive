/**
 * Generates the fluid type and space tokens in src/lib/styles/tokens.css.
 *
 * Breakpoint-based scaling: each style has a target size at 375, 768, 1440 and
 * 2560px. We emit one clamp() per range inside a media query, so each range
 * starts exactly where the previous one ended and there are no jumps. Values
 * combine rem with vw and are bounded in rem, so they still respond to browser
 * zoom and user font-size settings (WCAG 1.4.4).
 *
 * Run: node scripts/type-scale.js > src/lib/styles/generated-scale.css
 */

const BREAKPOINTS = [375, 768, 1440, 2560];
const ROOT = 16;

/** Target px sizes at each breakpoint. */
const TYPE = {
	// Effect page title: uppercase, heaviest weight, centred.
	display: [44, 80, 132, 200],
	// Archive page title.
	'step-5': [34, 48, 64, 92],
	// Section headings ("How it works").
	'step-4': [22, 26, 32, 42],
	// Overview / lead paragraph, light weight.
	'step-3': [19, 22, 26, 34],
	// Archive card name, sub-headings.
	'step-2': [17, 18, 20, 25],
	// Body copy.
	'step-1': [16, 16.5, 18, 22]
};

/** Fluid layout spacing, px at each breakpoint. */
const SPACE = {
	// Outer page margin.
	gutter: [20, 32, 40, 72],
	// Grid column gap.
	'grid-gap': [16, 24, 32, 48],
	// Gap between major page sections.
	section: [64, 96, 136, 200],
	// Whitespace around the effect page title.
	title: [48, 80, 120, 180]
};

const rem = (px) => +(px / ROOT).toFixed(4);

/**
 * clamp() for one breakpoint range. Slope is per 1vw; the intercept is the rem
 * part that makes the line pass through (bpMin, min).
 */
function clampRange(min, max, bpMin, bpMax) {
	if (min === max) return `${rem(min)}rem`;
	const slopeVw = ((max - min) / (bpMax - bpMin)) * 100;
	const interceptRem = rem(min - (slopeVw / 100) * bpMin);
	const lo = Math.min(min, max);
	const hi = Math.max(min, max);
	return `clamp(${rem(lo)}rem, ${interceptRem}rem + ${slopeVw.toFixed(4)}vw, ${rem(hi)}rem)`;
}

function emit(prefix, table) {
	const names = Object.keys(table);
	const lines = [];

	// Below the first breakpoint: fixed at the smallest target.
	lines.push(':root {');
	for (const n of names) lines.push(`\t--${prefix}${n}: ${rem(table[n][0])}rem;`);
	lines.push('}');

	for (let i = 0; i < BREAKPOINTS.length - 1; i++) {
		const [bpMin, bpMax] = [BREAKPOINTS[i], BREAKPOINTS[i + 1]];
		lines.push('');
		lines.push(`@media (width >= ${bpMin}px) {`);
		lines.push('\t:root {');
		for (const n of names) {
			lines.push(`\t\t--${prefix}${n}: ${clampRange(table[n][i], table[n][i + 1], bpMin, bpMax)};`);
		}
		lines.push('\t}');
		lines.push('}');
	}

	// Above the last breakpoint: fixed at the largest target.
	const last = BREAKPOINTS.at(-1);
	lines.push('');
	lines.push(`@media (width >= ${last}px) {`);
	lines.push('\t:root {');
	for (const n of names) lines.push(`\t\t--${prefix}${n}: ${rem(table[n].at(-1))}rem;`);
	lines.push('\t}');
	lines.push('}');

	return lines.join('\n');
}

const header = `/* Generated by scripts/type-scale.js. Do not edit by hand. */\n/* Targets: ${BREAKPOINTS.join(' / ')}px */\n`;
process.stdout.write(`${header}\n${emit('', TYPE)}\n\n${emit('space-fluid-', SPACE)}\n`);
