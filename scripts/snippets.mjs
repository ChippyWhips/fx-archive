/**
 * Builds one self-contained HTML snippet per effect into src/generated/snippets/.
 *
 * Pasted into an empty HTML file the snippet runs as is: no build step, no site
 * code. three.js comes from a CDN through an import map, pinned to the exact
 * version the site uses. Run after changing a demo or the shared host:
 *
 *   node scripts/snippets.mjs [slug ...]
 */

import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { schedule } from '../src/content/schedule.js';

const pkg = JSON.parse(await readFile('package.json', 'utf8'));
const THREE = pkg.dependencies.three;
const CDN = `https://cdn.jsdelivr.net/npm/three@${THREE}/build/three.module.js`;

const slugs = process.argv.slice(2).length > 0 ? process.argv.slice(2) : schedule.slugs;

const css = (await readFile('scripts/snippet/snippet.css', 'utf8')).trim();
const host = (await readFile('scripts/snippet/host.js', 'utf8')).trim();

await mkdir('src/generated/snippets', { recursive: true });

/** @param {string} text */
const escape = (text) => text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

for (const slug of slugs) {
	const entry = `src/lib/effects/${slug}/demo.js`;
	const source = await readFile(entry, 'utf8');

	// Bundled, not minified: the snippet is meant to be read and edited.
	const result = await build({
		entryPoints: [entry],
		bundle: true,
		format: 'esm',
		target: 'es2022',
		external: ['three'],
		write: false,
		legalComments: 'none'
	});

	const demo = result.outputFiles[0].text.trim();
	const usesThree = /from\s*["']three["']/.test(demo);

	const html = `<!doctype html>
<html lang="en-GB">
<head>
<meta charset="utf-8">
<title>${slug}</title>
${usesThree ? `<script type="importmap">\n{ "imports": { "three": "${CDN}" } }\n</script>\n` : ''}<style>
${css}
</style>
</head>
<body>

<div class="vv">
	<canvas></canvas>
	<div class="vv-panel"></div>
</div>

<script type="module">
${demo}

${host}
</script>

</body>
</html>
`;

	await writeFile(
		`src/generated/snippets/${slug}.js`,
		`// Generated by scripts/snippets.mjs. Do not edit.\n` +
			`export const snippet = \`${escape(html)}\`;\n` +
			`export const demo = \`${escape(source.trim())}\`;\n`
	);
	console.log(`snippets: ${slug} (${(html.length / 1024).toFixed(1)}KB)`);
}
